// Судьба игрока одной строкой. Мелочь, но она была написана дважды — на
// экране финала и на странице сохранённых итогов, — и тексты успели
// разойтись: «убит ночью 3» против «изгнан городом (день 2)».

import { describe, it, expect } from "vitest";
import { fateText } from "../src/lib/mafia-fate";

describe("судьба игрока", () => {
  it("называет и причину, и когда", () => {
    expect(fateText("mafia", 3)).toBe("убит мафией, ночь 3");
    expect(fateText("maniac", 3)).toBe("убит маньяком, ночь 3");
    expect(fateText("vote", 2)).toBe("изгнан городом, день 2");
  });

  it("выживший и ушедший — без дня", () => {
    expect(fateText(null, null)).toBe("выжил");
    expect(fateText(undefined, undefined)).toBe("выжил");
    expect(fateText("left", 4)).toBe("вышел из партии");
  });

  it("паритет — не «выжил»", () => {
    // Мафия побеждает, когда её стало не меньше остальных: оставшийся мирный
    // никуда не денется, и называть это выживанием было издёвкой.
    expect(fateText("overrun", 3)).toBe("остался с мафией лицом к лицу");
  });

  it("без дня строка не обрывается хвостом", () => {
    // day приходит из базы и бывает пустым у старых партий.
    expect(fateText("mafia", null)).toBe("убит мафией, ночь");
  });
});
