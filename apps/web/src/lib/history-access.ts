// Кто какие партии Алиаса видит в истории.
//
// Правило не новое: экран итогов (GET /api/games/[id]) давно пускает и
// владельца, и любого участника комнаты. Отставал только список — онлайн-партию
// в нём видел один хост, хотя играли шестеро. Здесь это правило записано один
// раз, чтобы список, статистика и итоги не разошлись.

import type { Prisma } from "@prisma/client";

/**
 * Партии, которые человек вправе видеть.
 *
 * `ownerKey` — тот, кто партию завёл: у локальной это устройство, у онлайновой
 * хост. Остальные участники находятся через комнату. Тех, кто из неё вышел, не
 * отсекаем: партия с ними была, и в истории ей место. У партии с удалённой
 * комнатой проверять участие уже не по чему — она остаётся у владельца.
 */
export function visibleGamesWhere(userId: string): Prisma.GameWhereInput {
  return {
    OR: [{ ownerKey: userId }, { room: { participants: { some: { userId } } } }],
  };
}
