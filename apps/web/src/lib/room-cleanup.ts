// Уборка комнаты, от которой осталась только строка в Postgres.
//
// Живое состояние партии живёт в Redis и умирает по TTL: комната, где никого
// не осталось, — через десять минут. Postgres об этом никто не уведомляет, и
// код становится зомби: по нему пускают, а сокет тут же отвечает «комнаты
// нет», партия же навсегда остаётся «в процессе» и зовёт «продолжить» туда,
// где продолжать нечего.
//
// Раньше этот блок дословно повторялся во входе в Алиас и во входе в Мафию.

import prisma from "@/lib/prisma";

/**
 * Закрыть комнату, живого состояния которой больше нет.
 *
 * Идемпотентна: повторный вызов ничего не меняет. Партию закрываем вместе с
 * комнатой — счёт в ней уже сохранён, дописывать нечего. У Мафии строка партии
 * появляется только в момент финала, поэтому закрывать там нечего.
 */
export async function closeAbandonedRoom(code: string): Promise<void> {
  await prisma.room
    .updateMany({
      where: { code, status: { not: "FINISHED" } },
      data: { status: "FINISHED", endedAt: new Date() },
    })
    .catch(() => {});
  await prisma.game
    .updateMany({
      where: { room: { code }, status: "IN_PROGRESS" },
      data: { status: "FINISHED", finishedAt: new Date() },
    })
    .catch(() => {});
}
